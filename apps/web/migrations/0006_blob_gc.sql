-- 孤児 blob の回収 (Phase 3-5b)。
--
-- 3-1 から 3-5a までで台帳は「所有」(`user_blobs`) と「参照」(`blob_refs`) を持ったが、
-- **実体を消す経路がまだ無い**。所有を手放しても消えるのは計上だけで、誰にも計上されず
-- 誰にも参照されていない実体が R2 に残り続ける。ここを回収する側の器を足す。

-- 孤児と**気付いた**時刻。回収まで待つ猶予はここから数える。
--
-- `created_at` から数えない理由: 上げた直後の blob はまだどのリビジョンからも参照されて
-- いないが、持ち込んだ人に計上されている (3-1) ので孤児ではない。孤児になるのは
-- **最後の所有者が手放した瞬間**で、その時刻は `blobs` のどの列にも無い。
--
-- NULL は「孤児ではない」。所有か参照が戻れば NULL に戻す (復活) ので、この列は
-- 回収待ちの行だけが値を持つ。
ALTER TABLE blobs ADD COLUMN orphaned_at INTEGER;

-- 回収の対象を引く経路。印の付いた行は全体のごく一部なので、部分インデックスにする
-- (印を立てる側は `blobs` の全走査で、そちらはインデックスで速くならない)。
CREATE INDEX blobs_orphaned ON blobs (orphaned_at) WHERE orphaned_at IS NOT NULL;

-- 回収を回す側の進捗。
--
-- 今のところ持つのは**参照台帳のバックフィル**だけ (3-5a より前に R2 へ書き出された
-- リビジョンは `blob_refs` に無い。埋めずに回収を始めると、既存の作品が使っている実体を
-- 全部孤児と見なす)。R2 の走査は 1 回の起動で終わらないので、続きの位置を持ち越す。
--
-- 汎用の key-value にしてあるのは、この種の「バッチが持ち越す状態」が回収以外にも
-- 出てくるため (Phase 4 の同期・サムネイル)。行数は数件で、型は用途ごとに解釈する。
CREATE TABLE gc_state (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL,
  updated_at INTEGER NOT NULL
) STRICT;

-- 参照台帳 (Phase 3-5a)。
--
-- `user_blobs` が「誰に計上するか」(所有) を持つのに対し、こちらは「どのリビジョンが
-- 使っているか」(参照) を持つ。ADR 0003 の補足のとおり、この 2 つは別物で、別の表が要る。
-- 所有はクォータのため、参照は**回収してよいかの判断**のためにある。
--
-- 誰も所有していないが公開済みの作品が参照している blob は普通に生まれる
-- (作った人が作品を残したままアセットだけ手放した場合 — 3-4b)。所有だけを見て
-- 回収すると、閲覧中の作品が理由も無く壊れる。
--
-- **同じ台帳を 2 つの読み方で使う。**
--   - 回収 (3-5b): 全期間。過去リビジョンが参照する実体は消さない
--   - 手放し (3-5a の `sketchesUsingBlob`): 今配信しているリビジョンだけ。手放しても
--     配信中の作品は壊れない (実体は残る) ので、断る理由は「次の保存が通らなくなる」
--     ことに限られる。過去まで数えると、一度使った実体は作品から外しても永久に
--     手放せなくなる

-- 参照の主体は作品ではなく、**R2 にあるリビジョンスナップショット**。
--
-- 守りたいのは「公開済みのリビジョンが参照する blob」で、それが実際に配られる経路は
-- D1 のポインタ → R2 の `gists/{gistId}/{revision}.json` (ADR 0011)。配られる実体と
-- 同じ単位で数えないと台帳と現実がずれる。`sketches` 側で数えると、Gist を切り離した
-- 作品 (`detachGist` は `current_revision` を落とすが R2 のオブジェクトは残す) の
-- 過去リビジョンが台帳から消え、まだ配られうる blob を孤児と誤判定してしまう。
CREATE TABLE blob_refs (
  gist_id TEXT NOT NULL,
  -- Gist のリビジョン SHA。R2 のキーと同じ組で不変。
  revision TEXT NOT NULL,
  -- **`blobs(sha256)` への外部キーは張らない。**
  -- マニフェストは利用者が書けるので、実体の無い sha256 も書ける。外部キーがあると
  -- その保存で参照の記録だけが失敗し、配信のポインタが進まなくなる。宙に浮いた行は
  -- 回収側 (3-5b) が blobs を起点に引く限り無害で、後からその実体が上がってきた
  -- ときには最初から守られる形になる。
  sha256 TEXT NOT NULL,
  created_at INTEGER NOT NULL,
  -- 同じリビジョンを二度書き出しても行は増えない (保存の再試行・閲覧時の fill)。
  PRIMARY KEY (gist_id, revision, sha256)
) STRICT;

-- 回収の判定は「この blob を参照している行があるか」なので、blob 側から引ける形が要る
-- (主キーの先頭は gist_id なので、これが無いと全表走査になる)。
CREATE INDEX blob_refs_by_blob ON blob_refs (sha256);
